#!/usr/bin/env python3
"""Main menu background map: the station plaza at dusk (scripts/chapterbackgrounds.txt -> background_c17).

    python make_background_c17.py        (after prep_rp_c17_02_plaza.py)

Takes the generated rp_c17_02_plaza.vmf, removes everything that belongs to play (transitions, dialog
and quest triggers, the player's start), puts a still camera at the station portico looking over the
square at the Breen screen and starts the clock at 19:10 - the street lamps come on while the menu is
open (night lamps of the deferred light converter). Compile: compile_map.ps1 -Map background_c17.
"""
import os
import sys

sys.path.insert(0, r"E:\SourceModding\HL2RPMSOURCE\.claude\skills\hl2rpm-hammer\scripts")
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from vmf import VMF  # noqa: E402
from slice_kit import timecycle, lower  # noqa: E402

MAPSRC = r"E:\XBLAH's modding tool\content\Mapbase\hl2rpm\mapsrc"
SRC = os.path.join(MAPSRC, "rp_c17_02_plaza.vmf")
DST = os.path.join(MAPSRC, "background_c17.vmf")

CAM_POS = (-2960, -2060, 150)
CAM_ANG = "-6 6 0"


def main():
    m = VMF.load(SRC)
    removed = 0
    for e in list(m.entities()):
        cls = lower(e.classname)
        if cls in ("trigger_changelevel", "trigger_transition", "trigger_dialog_start", "trigger_rpg",
                   "trigger_rpg_zone", "info_player_start", "logic_autosave"):
            m.delete(e)
            removed += 1
    m.add_entity("info_player_start", (CAM_POS[0] - 40, CAM_POS[1], 64), angles="0 6 0", spawnflags="1")
    cam = m.add_entity("point_viewcontrol", CAM_POS, targetname="menu_camera", angles=CAM_ANG,
                       spawnflags="44", wait="0", speed="0", acceleration="0", deceleration="0")
    la = m.add_entity("logic_auto", (CAM_POS[0], CAM_POS[1], CAM_POS[2] + 32), spawnflags="1")
    m.add_output(la, "OnMapSpawn", "menu_camera", "Enable", "", 0.1, 1)
    timecycle(m, (CAM_POS[0], CAM_POS[1] + 40, CAM_POS[2]), 19.15, time_scale="4")
    m.world.set("comment", "HL2RPM main menu background, generated by hl2rpm_extras/tools/make_background_c17.py "
                "from rp_c17_02_plaza.vmf - do not edit by hand")
    m.save(DST, backup=False)
    print("wrote", DST, "(%d play entities removed)" % removed)


if __name__ == "__main__":
    main()
