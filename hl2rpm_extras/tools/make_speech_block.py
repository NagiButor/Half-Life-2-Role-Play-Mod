"""Lines of HL2 / EP1 / EP2 NPCs that talk to Gordon Freeman ("Freeman!", "Hey, doc", "Gordon")
-> scripts/hl2rpm_speech_block.txt of the mod: the server never lets an NPC say them
(game/server/hl2rpm_barks.cpp, RPMSpeech::Allow). The list is built from the close captions:
their keys are the sound script names of the lines (npc_citizen.abouttime01); scenes of the
generic NPCs are named after the same lines (scenes/npc/male01/abouttime01.vcd).

    python make_speech_block.py [<HL2 unpacked folder>] [<mod folder>]
"""
import os
import re
import sys

SRC = sys.argv[1] if len(sys.argv) > 1 else r"E:\SourceModding\UsefulStuff\Source sdk 2013 HL2 unpacked vpk"
MOD = sys.argv[2] if len(sys.argv) > 2 else r"E:\Steam\steamapps\sourcemods\hl2rpm"
PATTERN = re.compile(r"freeman|gordon|\bdoctor\b|\bdr\.|\bdoc\b|\bmr\. ?f", re.I)


def load(path):
    raw = open(path, "rb").read()
    text = raw.decode("utf-16") if raw[:2] in (b"\xff\xfe", b"\xfe\xff") else raw.decode("utf-8", "replace")
    return re.findall(r'"([^"]+)"\s+"([^"]*)"', text)


def main():
    names = {}
    for game in ("hl2", "episodic", "ep2"):
        path = os.path.join(SRC, game, "resource", "closecaption_english.txt")
        if not os.path.isfile(path):
            print("no", path)
            continue
        n = 0
        for key, text in load(path):
            clean = re.sub(r"<[^>]*>", "", text)
            if "commentary" in key.lower():
                continue        # developer commentary, not NPC speech
            if PATTERN.search(clean):
                names.setdefault(key.lower(), clean.strip())
                n += 1
        print("%s: %d lines" % (game, n))
    out = os.path.join(MOD, "scripts", "hl2rpm_speech_block.txt")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Lines of HL2 NPCs that speak to Gordon Freeman: HL2RPM NPCs never say them.\n")
        f.write("// Generated by hl2rpm_extras/tools/make_speech_block.py from the close captions; one sound script name per line.\n")
        for key in sorted(names):
            f.write("%s\t// %s\n" % (key, names[key][:90].replace("\n", " ")))
    print("%d names -> %s" % (len(names), out))


if __name__ == "__main__":
    main()
