class Seq:
    def __init__(self, name, clip, activity=None, weight=1, loop=None, events=(), fadein=0.2, fadeout=0.2,
                 extra="", blend=None):
        """clip: a Clip, or a list of clips blended by a pose parameter: blend = (param, min, max)"""
        self.name = name
        self.clips = list(clip) if isinstance(clip, (list, tuple)) else [clip]
        self.blend = blend
        clip = self.clips[0]
        self.clip = clip
        self.activity = activity
        self.weight = weight
        self.loop = clip.loop if loop is None else loop
        self.events = list(events) + list(getattr(clip, "events", []))
        self.fadein = fadein
        self.fadeout = fadeout
        self.extra = extra


def library_paths(skel):
    src = os.path.join(SRC_ROOT, skel)
    return src, "hl2rpm/anims/rpm_%s_anims.mdl" % skel


class Cached:
    """a sequence built earlier: its SMDs and QC line are reused (make_anims.py --only)"""

    def __init__(self, name):
        self.name = name


def write_library(skel, seqs, rig):
    """SMDs + QC of the library; returns (QC path, pose parameters). Sequences given as Cached
    reuse what an earlier build wrote (meta/<name>.json + their SMDs)."""
    src, mdl = library_paths(skel)
    meta_dir = os.path.join(src, "meta")
    os.makedirs(meta_dir, exist_ok=True)
    smd.write_reference(os.path.join(src, "ref.smd"), rig)
    qc = ['// generated by hl2rpm_extras/tools/anims (rpm_anim.build) - do not edit',
          '$modelname "%s"' % mdl, '$origin 0 0 0 -90', '$body "ref" "ref.smd"']
    lines, params, keep = [], {}, set()
    for s in seqs:
        mp = os.path.join(meta_dir, s.name + ".json")
        if isinstance(s, Cached):
            if not os.path.exists(mp):
                raise SystemExit("no cached sequence %s - build it once without --only" % s.name)
            meta = json.load(open(mp, encoding="utf-8"))
        else:
            base = re.sub(r"[^A-Za-z0-9_]+", "_", s.name)
            files = []
            for k, c in enumerate(s.clips):
                fn = "a_%s%s.smd" % (base, "" if len(s.clips) == 1 else "_b%d" % k)
                smd.write_clip(os.path.join(src, fn), c)
                files.append(fn)
            meta = {"name": s.name, "files": files, "blend": list(s.blend) if s.blend else None, "fps": s.clip.fps,
                    "fadein": s.fadein, "fadeout": s.fadeout, "loop": bool(s.loop), "activity": s.activity,
                    "weight": s.weight, "extra": s.extra, "events": [[int(f), e, o] for f, e, o in s.events]}
            with open(mp, "w", encoding="utf-8") as f:
                json.dump(meta, f, indent=1)
        keep.update(meta["files"])
        if meta["blend"]:
            p = meta["blend"][0]
            params[p] = POSE_RANGES.get(p, (meta["blend"][1], meta["blend"][2]))
        line = '$sequence "%s" %s' % (meta["name"], " ".join('"%s"' % f for f in meta["files"]))
        if meta["blend"]:
            line += ' blend "%s" %g %g' % tuple(meta["blend"])
        line += " fps %.3f fadein %.2f fadeout %.2f" % (meta["fps"], meta["fadein"], meta["fadeout"])
        if meta["loop"]:
            line += " loop"
        if meta["activity"]:
            line += " activity %s %d" % (meta["activity"], meta["weight"])
        if meta["extra"]:
            line += " " + meta["extra"]
        if meta["events"]:
            line += " {\n" + "\n".join('\t{ event %s %d "%s" }' % (e, f, o) for f, e, o in meta["events"]) + "\n}"
        lines.append(line)
    for p, (lo, hi) in sorted(params.items()):
        qc.append('$poseparameter "%s" %g %g' % (p, lo, hi))
    qc += lines
    # SMDs of sequences that are gone
    for f in os.listdir(src):
        if f.startswith("a_") and f.endswith(".smd") and f not in keep:
            os.remove(os.path.join(src, f))
    path = os.path.join(src, "rpm_%s_anims.qc" % skel)
    with open(path, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(qc) + "\n")
    return path, params


def write_hook(skel, pose_params=None):
    """the thin <shared>.mdl of the mod: the original (copied) + the library; the library's pose
    parameters are declared here too (as Mapbase's male_shared repeats those of its original)"""
    pose_params = pose_params or {}
    info = SKELETONS[skel]
    shared = info["shared"]
    src, lib = library_paths(skel)
    fs = R.game_fs()
    base = os.path.basename(shared)[:-4]
    copy_rel = "models/hl2rpm/anims/mb_%s.mdl" % base
    copy_abs = os.path.join(MOD, copy_rel.replace("/", os.sep))
    # the original must come from Mapbase / HL2, never from our own thin hook in the mod
    data = None
    for root in fs_roots_without_mod(fs):
        data = root(shared)
        if data:
            break
    if data is None:
        raise SystemExit("can't find the original " + shared)
    os.makedirs(os.path.dirname(copy_abs), exist_ok=True)
    if not os.path.exists(copy_abs) or open(copy_abs, "rb").read() != data:
        with open(copy_abs, "wb") as f:
            f.write(data)
    hook_dir = os.path.join(src, "hook")
    os.makedirs(hook_dir, exist_ok=True)
    rig = R.Rig.from_model(info["rig"])
    smd.write_reference(os.path.join(hook_dir, "ref.smd"), rig)
    stub = rig.rest_clip(2)
    smd.write_clip(os.path.join(hook_dir, "stub.smd"), stub)
    qc = ['// generated by hl2rpm_extras/tools/anims (rpm_anim.build): %s = the original (%s) + the HL2RPM library'
          % (shared, copy_rel), '$modelname "%s"' % shared[len("models/"):], '$origin 0 0 0 -90',
          '$body "ref" "ref.smd"',
          '$includemodel "%s"' % copy_rel[len("models/"):], '$includemodel "%s"' % lib] + \
         ['$poseparameter "%s" %g %g' % (k, lo, hi) for k, (lo, hi) in sorted(pose_params.items())] + [
          '$sequence "rpm_%s_hook" "stub.smd" fps 30' % skel]
    path = os.path.join(hook_dir, base + ".qc")
    with open(path, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(qc) + "\n")
    return path


def fs_roots_without_mod(fs):
    """readers of a game file that skip the mod's own folders (its thin hooks)"""
    mod = os.path.normcase(os.path.abspath(MOD))
    out = []
    for kind, root in fs.sources:
        if kind == "dir" and os.path.normcase(os.path.abspath(root)).startswith(mod):
            continue
        out.append(lambda rel, kind=kind, root=root: _read_root(kind, root, rel))
    return out


def _read_root(kind, root, rel):
    rel = rel.replace("\\", "/").lower()
    if kind == "dir":
        p = os.path.join(root, rel.replace("/", os.sep))
        return open(p, "rb").read() if os.path.isfile(p) else None
    return root.read(rel) if root.has(rel) else None


