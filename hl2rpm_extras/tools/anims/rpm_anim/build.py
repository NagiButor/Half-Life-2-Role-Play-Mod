POSE_RANGES = {"rpm_seat_h": (0.0, 40.0)}     # every set blends over its own part of the range


def write_actbusy(entries):
    """scripts/actbusy.txt of the mod = the stock one (Mapbase / HL2) + the library's entries:
    entries = [(name, {"busy_sequence": .., "entry_sequence": .., "exit_sequence": .., ...})]"""
    fs = R.game_fs()
    data = None
    for root in fs_roots_without_mod(fs):
        data = root("scripts/actbusy.txt")
        if data:
            break
    if data is None:
        raise SystemExit("no stock scripts/actbusy.txt")
    text = data.decode("utf-8", "replace").replace("\r\n", "\n").rstrip()
    end = text.rfind("}")
    lines = ["", "\t// ---- HL2RPM animation library (hl2rpm_extras/tools/anims: make_anims.py) ----"]
    for name, kv in entries:
        lines.append('\t"%s"' % name)
        lines.append("\t{")
        for k, v in kv.items():
            lines.append('\t\t"%s"\t"%s"' % (k, v))
        lines.append("\t}")
    out = text[:end].rstrip() + "\n" + "\n".join(lines) + "\n}\n"
    path = os.path.join(MOD, "scripts", "actbusy.txt")
    with open(path, "w", encoding="utf-8", newline="\r\n") as f:
        f.write("// HL2RPM: generated by hl2rpm_extras/tools/anims/make_anims.py - the stock file of Mapbase + the library\n")
        f.write(out)
    return path


def write_seat_params(rows):
    """scripts/hl2rpm_anim_seats.txt: how every sitting animation of the library sits (the Creation Kit
    fits its markers to furniture with these, dlgedit/world/seatfit.py): rows = [(actbusy name, {key: number})]"""
    lines = ['// HL2RPM: generated by hl2rpm_extras/tools/anims/make_anims.py - the sitting animations of the library',
             '"AnimSeats"', "{"]
    for name, vals in rows:
        lines.append('\t"%s"' % name)
        lines.append("\t{")
        for k, v in vals.items():
            lines.append('\t\t"%s"\t"%g"' % (k, v))
        lines.append("\t}")
    lines.append("}")
    path = os.path.join(MOD, "scripts", "hl2rpm_anim_seats.txt")
    with open(path, "w", encoding="utf-8", newline="\r\n") as f:
        f.write("\n".join(lines) + "\n")
    return path
