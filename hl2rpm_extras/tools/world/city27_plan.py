"""City-27 world layout: zones, transitions, features. Single source of truth for plans.

Coordinate frame: metres of game world. Origin = Citadel axis. +X east, +Y north.
1 Hammer unit = 0.0254 m, so 1 m = 39.37 HU; a BSP spans at most 32768 HU = 832 m.

Compression is radial around the Citadel (see compress_radius): the inner city is
2.2:1, the belt 3.2:1, the near wasteland 6:1, the far wasteland 10:1. Real places
keep their true bearing; only their distance is squashed. Far zones are also pulled
in by hand so that the whole world fits into a 3.0 x 2.75 km footprint.
"""
import math

LAT0, LON0 = 47.5140, 19.0850        # Citadel axis: Városliget, Budapest
KY = 111300.0
KX = 111300.0 * math.cos(math.radians(LAT0))

RINGS = [(0, 1100, 2.2), (1100, 3000, 3.2), (3000, 7000, 6.0), (7000, 20000, 10.0)]


def real_xy(lat, lon):
    return ((lon - LON0) * KX, (lat - LAT0) * KY)


def compress_radius(r):
    acc = 0.0
    for a, b, k in RINGS:
        if r <= b:
            return acc + (r - a) / k
        acc += (b - a) / k
    return acc


def game_xy(lat, lon):
    x, y = real_xy(lat, lon)
    r = math.hypot(x, y)
    if r < 1e-6:
        return (0.0, 0.0)
    k = compress_radius(r) / r
    return (x * k, y * k)


