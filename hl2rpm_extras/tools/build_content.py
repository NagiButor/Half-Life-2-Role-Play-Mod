def tok_part(s):
    return re.sub(r"[^A-Za-z0-9_]", "_", s).upper()


def is_int(s, signed=True):
    return re.fullmatch(r"[+-]?\d+" if signed else r"\d+", s.strip() if s else "") is not None


def split_list(s):
    return [p.strip() for p in re.split(r"[,;]", s) if p.strip()]


def md_cell(s):
    return (s or "").replace("\\", "\\\\").replace("|", "\\|").replace("\r", "").replace("\n", "<br>")


