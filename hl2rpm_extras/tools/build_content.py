def read_text_file(path):
    """-> (text, problem). Понимает UTF-8 (с BOM и без), UTF-16 с BOM; cp1251 - с предупреждением."""
    raw = open(path, "rb").read()
    if raw[:2] in (b"\xff\xfe", b"\xfe\xff"):
        return raw.decode("utf-16"), None
    if raw[:3] == b"\xef\xbb\xbf":
        raw = raw[3:]
    try:
        return raw.decode("utf-8"), None
    except UnicodeDecodeError as e:
        return raw.decode("cp1251", errors="replace"), ("файл не в UTF-8 (байт %d), прочитан как cp1251 - "
                                                        "пересохраните в UTF-8" % e.start)


class KV(object):
    __slots__ = ("_key", "k", "value", "children", "line", "cond")

    def __init__(self, key, value=None, line=0):
        self.key = key
        self.value = value
        self.children = [] if value is None else None
        self.line = line
        self.cond = None

    @property
    def key(self):
        return self._key

    @key.setter
    def key(self, v):
        self._key = v
        self.k = v.lower()       # ключи KeyValues сравниваются без учёта регистра

    @property
    def is_block(self):
        return self.value is None

    def leaf(self, key):
        key = key.lower()
        for c in self.children:
            if c.value is not None and c.k == key:
                return c
        return None

    def get(self, key, default=None):
        n = self.leaf(key)
        return n.value if n is not None else default

    def block(self, key):
        key = key.lower()
        for c in self.children:
            if c.value is None and c.k == key:
                return c
        return None

    def blocks(self):
        return [c for c in self.children if c.value is None]

    def all(self, key):
        key = key.lower()
        return [c for c in self.children if c.k == key]

    def remove(self, node):
        self.children = [c for c in self.children if c is not node]


def _tokenize(text, src, diag, multiline_level):
    """Токены: ('s', str) в кавычках, ('b', str) без кавычек, ('{',), ('}',), ('c', '[$X]'); + номер строки."""
    i, n, line = 0, len(text), 1
    out = []
    while i < n:
        ch = text[i]
        if ch == "\n":
            line += 1
            i += 1
            continue
        if ch in " \t\r\f\v\ufeff":
            i += 1
            continue
        if ch == "/" and text.startswith("//", i):
            j = text.find("\n", i)
            i = n if j < 0 else j
            continue
        if ch == "{" or ch == "}":
            out.append((ch, ch, line))
            i += 1
            continue
        if ch == '"':
            start = line
            i += 1
            buf = []
            closed = False
            multi = False
            while i < n:
                c = text[i]
                if c == "\\" and i + 1 < n:
                    nx = text[i + 1]
                    if nx == '"':
                        buf.append('"')
                        i += 2
                        continue
                    if nx == "\\":
                        buf.append("\\")
                        i += 2
                        continue
                    if nx == "n":
                        buf.append("\n")
                        i += 2
                        continue
                    if nx == "t":
                        buf.append("\t")
                        i += 2
                        continue
                    buf.append(c)
                    i += 1
                    continue
                if c == '"':
                    closed = True
                    i += 1
                    break
                if c == "\n":
                    line += 1
                    multi = True
                    if c == "\n" and buf and buf[-1] == "\r":
                        buf.pop()
                buf.append(c)
                i += 1
            if not closed:
                diag.error(src, start, "", "строка в кавычках не закрыта до конца файла")
            elif multi:
                msg = ("значение в кавычках, начатое в строке %d, продолжается на строке %d - не закрыта "
                       "кавычка? Перенос строки в тексте пишите как \\n" % (start, line))
                diag.add(multiline_level, src, start, "", msg)
            out.append(("s", "".join(buf), start))
            continue
        if ch == "[":
            j = text.find("]", i)
            if j > 0 and "\n" not in text[i:j] and text[i + 1:i + 2] in ("$", "!"):
                out.append(("c", text[i:j + 1], line))
                i = j + 1
                continue
        j = i
        while j < n and text[j] not in ' \t\r\n\f\v{}"':
            if text.startswith("//", j):
                break
            j += 1
        out.append(("b", text[i:j], line))
        i = j
    return out


def kv_parse(text, src, diag, multiline_level="error"):
    """KeyValues: строки в кавычках с \\" \\\\ \\n \\t, слова без кавычек, // комментарии, вложенные
    блоки, повторяющиеся ключи (порядок сохраняется), условия [$X] (сохраняются, не вычисляются)."""
    root = KV("<root>")
    stack = [root]
    toks = _tokenize(text, src, diag, multiline_level)
    i, n = 0, len(toks)
    while i < n:
        typ, val, ln = toks[i]
        if typ == "}":
            if len(stack) == 1:
                diag.error(src, ln, "", "лишняя закрывающая скобка }")
            else:
                stack.pop()
            i += 1
            continue
        if typ == "{":
            diag.error(src, ln, "", "блок { без имени")
            node = KV("", line=ln)
            stack[-1].children.append(node)
            stack.append(node)
            i += 1
            continue
        if typ == "c":
            if stack[-1].children:
                stack[-1].children[-1].cond = val
            i += 1
            continue
        key, kline = val, ln
        if typ == "b" and key.lower() in ("#base", "#include"):
            diag.warn(src, ln, "", "%s не поддерживается - пропущено" % key)
            i += 2
            continue
        i += 1
        cond = None
        if i < n and toks[i][0] == "c":
            cond = toks[i][1]
            i += 1
        if i >= n:
            diag.error(src, kline, "", 'у ключа "%s" нет значения (конец файла)' % _shown(key))
            break
        typ2, val2, ln2 = toks[i]
        if typ2 == "{":
            node = KV(key, line=kline)
            node.cond = cond
            stack[-1].children.append(node)
            stack.append(node)
            i += 1
        elif typ2 == "}":
            diag.error(src, kline, "", 'у ключа "%s" нет значения (дальше сразу })' % _shown(key))
        else:
            node = KV(key, val2, line=kline)
            node.cond = cond
            i += 1
            if i < n and toks[i][0] == "c":
                node.cond = toks[i][1]
                i += 1
            stack[-1].children.append(node)
    for b in stack[1:]:
        diag.error(src, b.line, "", 'блок "%s" не закрыт (нет })' % _shown(b.key))
    return root


def _shown(key):
    k = key.replace("\r", "").replace("\n", "\u23ce").replace("\t", " ")
    return k if len(k) <= 40 else k[:37] + "..."


def _kv_q(s):
    # движок читает KV без escape-последовательностей: кавычку и перевод строки записать нельзя
    return s.replace('"', "'").replace("\r", "").replace("\n", " ")


def kv_dump(node, depth=0, out=None):
    if out is None:
        out = []
    for c in node.children:
        ind = "\t" * depth
        cond = (" " + c.cond) if c.cond else ""
        if c.is_block:
            out.append('%s"%s"%s' % (ind, _kv_q(c.key), cond))
            out.append(ind + "{")
            kv_dump(c, depth + 1, out)
            out.append(ind + "}")
        else:
            pad = "\t" * max(1, 4 - (len(c.key) + 2) // 4)
            out.append('%s"%s"%s"%s"%s' % (ind, _kv_q(c.key), pad, _kv_q(c.value), cond))
    return out


