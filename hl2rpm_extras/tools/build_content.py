    def text_issues(self, text, src, line, where, key, lang, option=False):
        if '"' in text:
            self.D.warn(src, line, where, '%s: в тексте двойные кавычки - пишите «ёлочки»' % key)
        if "\\" in text:
            self.D.warn(src, line, where, '%s: обратная косая черта в тексте - игра покажет её как есть' % key)
        if any(ord(ch) > 0xFFFF for ch in text):
            self.D.warn(src, line, where, '%s: символы вне BMP (эмодзи и т.п.) движок не покажет' % key)
        if len(text) > 4000:
            self.D.error(src, line, where, '%s: %d символов - предел строки локализации 4096' % (key, len(text)))
        if option and len(text.encode("utf-8")) > 250:
            self.D.warn(src, line, where, '%s: %d байт UTF-8 - длиннее 250 байт' % (key, len(text.encode("utf-8"))))

    def add_token(self, name, ru, en, src, line, where, file=None):
        key = name.upper()
        if len(key) > 120:
            self.D.error(src, line, where, 'имя токена длиннее 120 символов: %s' % name)
        if file is None:
            file = "rpg" if key.startswith("RPG_") else "dialog"
        t = self.tokens.get(key)
        if t is not None:
            if (t.ru, t.en) == (ru, en):
                self.D.warn(src, line, where, 'токен %s уже есть (%s:%d) с тем же текстом - используется повторно' % (name, t.src, t.line))
            else:
                self.D.error(src, line, where, 'токен %s уже определён в %s:%d с другим текстом' % (name, t.src, t.line))
            return t.name
        if key in self.engine_tokens:
            self.D.warn(src, line, where, 'токен %s есть и в resource/hl2rpm_<lang>.txt - конфликт' % name)
        self.tokens[key] = Token(name, ru, en, src, line, where, file)
        return name

    def tokenize_pair(self, blk, key, token, src, where, option=False, required=False):
        """Заменяет "key"/"key_en" на "#TOKEN". -> (token, ru, en, line) или None."""
        ru_n = blk.leaf(key)
        en_n = blk.leaf(key + "_en")
        if ru_n is None and en_n is None:
            if required:
                self.D.error(src, blk.line, where, 'нет "%s" / "%s_en"' % (key, key))
            return None
        ru = ru_n.value if ru_n is not None else None
        en = en_n.value if en_n is not None else None
        line = (ru_n or en_n).line
        if ru is not None and ru.startswith("#") and re.fullmatch(r"#[A-Za-z0-9_.\-]+", ru.strip()):
            if en_n is not None:
                self.D.warn(src, line, where, '%s уже токен (%s), %s_en не нужен - пропущен' % (key, ru, key))
                blk.remove(en_n)
            return None
        if ru is None or not ru.strip():
            self.D.error(src, line, where, 'нет русского текста "%s" (есть только %s_en)' % (key, key))
            ru = None
        if en is None or not en.strip():
            self.D.error(src, line, where, 'нет английского текста "%s_en"' % key)
            en = None
        for t, lang in ((ru, "ru"), (en, "en")):
            if t:
                self.text_issues(t, src, line, where, key if lang == "ru" else key + "_en", lang, option)
        name = self.add_token(token, ru, en, src, line, where)
        if ru_n is None:
            ru_n = en_n
            ru_n.key = key
        else:
            if en_n is not None:
                blk.remove(en_n)
        ru_n.value = "#" + name
        return (name, ru or "", en or "", line)

