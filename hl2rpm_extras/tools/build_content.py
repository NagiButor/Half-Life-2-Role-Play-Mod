    def load_characters(self):
        path = os.path.join(self.content, "characters.txt")
        src = "characters.txt"
        if not os.path.exists(path):
            self.D.warn(src, 0, "", "нет файла - голоса NPC не описаны")
            return
        text = self.read(path, src)
        if text is None:
            return
        root = kv_parse(text, src, self.D, "warn")
        blk = next((b for b in root.blocks()), None)
        if blk is None or blk.k != "characters":
            self.D.error(src, 1, "", 'корневой блок должен называться "Characters"')
            if blk is None:
                return
        for card in blk.children:
            if not card.is_block:
                self.D.error(src, card.line, "", 'ожидается блок голоса "%s" { ... }' % card.key)
                continue
            vid = card.key
            where = "голос " + vid
            if not re.fullmatch(r"[a-z0-9_]+", vid):
                self.D.error(src, card.line, where, "id голоса - строчная латиница, цифры, _ (это имя папки)")
            if vid in self.chars:
                self.D.error(src, card.line, where, "голос описан дважды")
                continue
            self.check_block(card, CHARACTER, src, where)
            info = {"id": vid, "line": card.line, "refs": []}
            for c in card.children:
                if not c.is_block:
                    info[c.k] = c.value
            refs = card.block("references")
            if refs is not None:
                for r in refs.blocks():
                    info["refs"].append((r.get("ru", ""), r.get("en", "")))
            if len(info["refs"]) < 3 and info.get("vo", "") not in ("none", "vanilla"):
                self.D.warn(src, card.line, where, "эталонных реплик меньше трёх (Part VI/02 §8)")
            self.chars[vid] = info
            for npc in split_list(info.get("npc", "")):
                n = npc.lower()
                if n.endswith("*"):
                    self.char_patterns.append((n[:-1], vid))
                    continue
                if n in self.char_npc and self.char_npc[n] != vid:
                    self.D.error(src, card.line, where, 'NPC %s уже привязан к голосу %s' % (n, self.char_npc[n]))
                self.char_npc[n] = vid
                spec = SPEC_NPCS.get(n)
                if spec is not None and spec != vid:
                    self.D.warn(src, card.line, where, 'по RPG_SPEC §11 у %s голос "%s"' % (n, spec or "—"))
        for n, v in SPEC_NPCS.items():
            if v and v not in self.chars:
                self.D.warn(src, 0, "", 'нет карточки голоса "%s" (%s, RPG_SPEC §11)' % (v, n))

    def voice_for(self, targetname):
        if not targetname:
            return None
        n = targetname.lower()
        if n in self.char_npc:
            return self.char_npc[n]
        if n in SPEC_NPCS:
            return SPEC_NPCS[n] or ""
        for p, v in self.char_patterns:
            if n.startswith(p):
                return v
        for p, v in NPC_PATTERNS:
            if n.startswith(p):
                return v
        return None

