    def build_quest_file(self, path, src):
        text = self.read(path, src)
        if text is None:
            return
        root = self.parse_checked(text, src)
        if root is None:
            return
        stem = os.path.splitext(os.path.basename(path))[0]
        quests = []
        for top in root.children:
            if not top.is_block:
                self.D.warn(src, top.line, "", 'ключ "%s" вне блока "Quest" - пропущен' % top.key)
                continue
            if top.k == "quest":
                quests.append((top, None))
            elif top.k == "quests":
                for q in top.blocks():
                    quests.append((q, q.key))
            else:
                self.D.error(src, top.line, "", 'корневой блок "%s": нужен "Quest" (или "Quests" со списком)' % top.key)
        if not quests:
            self.D.error(src, 1, "", 'нет блока "Quest" { ... }')
            return
        for q, name in quests:
            qid = self.compile_quest(q, src, default_id=name or (stem if len(quests) == 1 else None),
                                     embedded=False)
            if qid is None:
                continue
            if len(quests) == 1 and qid != stem and not stem.startswith("_"):
                self.D.note(src, q.line, "квест " + qid, 'имя файла "%s" не совпадает с id - в MOD будет scripts/quests/%s.txt' % (stem, qid))
            q.key = "Quest"
            out = KV("<root>")
            out.children.append(q)
            self.outputs.append((os.path.join(self.mod, "scripts", "quests", qid + ".txt"),
                                 self.render_kv(out, src), src, qid))

    def compile_quest(self, q, src, default_id=None, embedded=False):
        qid = (q.get("id") or (q.key if embedded else default_id) or "").strip()
        where = "квест " + (qid or "?")
        if not qid:
            self.D.error(src, q.line, where, 'нет "id"')
            return None
        if not re.fullmatch(r"[a-z0-9_]+", qid):
            self.D.error(src, q.line, where, 'id "%s": строчная латиница, цифры и _' % qid)
        if qid in self.quests:
            s, l = self.quests[qid]
            self.D.error(src, q.line, where, 'квест уже определён в %s:%d' % (s, l))
            return None
        self.quests[qid] = (src, q.line)
        if qid not in SPEC_QUESTS and not src.split("/")[-1].startswith("_"):
            self.D.warn(src, q.line, where, 'квеста нет в списке RPG_SPEC §11')
        self.check_block(q, QUEST_ROOT, src, where)
        if not embedded and q.leaf("id") is None:
            q.children.insert(0, KV("id", qid, q.line))
        QT = "Q_" + tok_part(qid)
        if q.get("category") == "faction" and not q.get("faction"):
            self.D.error(src, q.line, where, 'category faction требует "faction"')
        self.tokenize_pair(q, "title", QT + "_TITLE", src, where, required=True)
        self.tokenize_pair(q, "desc", QT + "_DESC", src, where)
        rw = q.block("rewards")
        if rw is not None:
            for c in rw.children:
                if c.is_block:
                    self.D.error(src, c.line, where + " / rewards", "ожидается «classname» «количество»")
                    continue
                self.check_item(c.key, src, c.line, where + " / rewards")
                if not is_int(c.value, False):
                    self.D.error(src, c.line, where + " / rewards", '%s = "%s": количество - число' % (c.key, c.value))
        oc = q.block("on_complete")
        if oc is not None:
            self.check_block(oc, {}, src, where + " / on_complete", effects=True)
        stages = q.block("stages")
        if stages is None:
            if not embedded:
                self.D.warn(src, q.line, where, 'нет блока "stages"')
        else:
            ids = []
            for st in stages.children:
                if not st.is_block:
                    self.D.error(src, st.line, where, 'stages: ожидается блок стадии "%s" { ... }' % st.key)
                    continue
                sw = "%s / стадия %s" % (where, st.key)
                if not is_int(st.key, False):
                    self.D.error(src, st.line, sw, "номер стадии - число")
                    continue
                n = int(st.key)
                if n in ids:
                    self.D.error(src, st.line, sw, "стадия повторяется")
                ids.append(n)
                self.check_block(st, STAGE, src, sw)
                self.tokenize_pair(st, "title", "%s_S%d_TITLE" % (QT, n), src, sw)
                self.tokenize_pair(st, "desc", "%s_S%d_DESC" % (QT, n), src, sw)
                if st.get("marker") and st.get("marker").lower().startswith("npc_"):
                    self.check_npc(st.get("marker"), src, st.leaf("marker").line, sw)
                soc = st.block("on_complete")
                if soc is not None:
                    self.check_block(soc, {}, src, sw + " / on_complete", effects=True)
                objs = st.block("objectives")
                if objs is not None:
                    for ob in objs.children:
                        ow = "%s / цель %s" % (sw, ob.key)
                        if not ob.is_block:
                            self.D.error(src, ob.line, ow, 'ожидается блок цели { "type" ... "target" ... }')
                            continue
                        self.check_block(ob, OBJECTIVE, src, ow)
                        t, tgt = ob.get("type"), (ob.get("target") or "").strip()
                        if not t:
                            self.D.error(src, ob.line, ow, 'нет "type"')
                        if not tgt:
                            self.D.error(src, ob.line, ow, 'нет "target"')
                            continue
                        if t == "talk":
                            self.check_npc(tgt, src, ob.line, ow)
                        elif t == "item":
                            self.check_item(tgt, src, ob.line, ow)
                        elif t == "flag":
                            self.flags_req[re.split(r"[=<>!]", tgt)[0]].append((src, ob.line))
                elif st.get("kill_target") is None and st.get("kill_targets") is None:
                    self.D.warn(src, st.line, sw, 'у стадии нет "objectives"')
            ids.sort()
            if ids and ids != list(range(ids[0], ids[0] + len(ids))):
                self.D.warn(src, stages.line, where, "пропуск в номерах стадий: %s" % ", ".join(map(str, ids)))
            if ids and ids[0] != 0:
                self.D.warn(src, stages.line, where, "стадии нумеруются с 0")
        self.strip_source_only(q)
        self.stats["quests"] += 1
        return qid

