def is_narration(s):
    t = s.strip()
    return bool(re.fullmatch(r"\*?\(.*\)\*?|\*[^*]+\*", t, re.S))


def atomic_write(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    if os.path.exists(path):
        with open(path, "rb") as f:
            if f.read() == data:
                return False
    tmp = path + ".tmp_build_content"
    with open(tmp, "wb") as f:
        f.write(data)
    os.replace(tmp, path)
    return True


