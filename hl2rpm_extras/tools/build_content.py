class Diag(object):
    LEVELS = {"error": "ERROR", "warn": "WARN ", "note": "NOTE "}

    def __init__(self):
        self.items = []

    def add(self, level, src, line, where, msg):
        self.items.append((level, src or "", line or 0, where or "", msg))

    def error(self, src, line, where, msg):
        self.add("error", src, line, where, msg)

    def warn(self, src, line, where, msg):
        self.add("warn", src, line, where, msg)

    def note(self, src, line, where, msg):
        self.add("note", src, line, where, msg)

    def format(self, item):
        level, src, line, where, msg = item
        loc = src + (":%d" % line if line else "")
        return "%s %s%s%s" % (self.LEVELS[level], loc, ("  " + where + ":") if where else ":", " " + msg)


