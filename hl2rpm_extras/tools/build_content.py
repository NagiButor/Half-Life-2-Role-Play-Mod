    def run(self):
        if not os.path.isdir(self.content):
            print("нет папки CONTENT: %s" % self.content)
            return 2
        self.load_rpg_data()
        self.load_characters()
        self.build_quests()
        self.build_dialogs()
        self.build_strings()
        self.cross_checks()

        if self.args.only:
            o = self.args.only.lower()
            for path, data, src, name in self.outputs:
                stem = os.path.splitext(os.path.basename(src))[0].lower()
                if o in (stem, (name or "").lower(), src.lower()):
                    self.only_srcs.add(src)
            for f in ("dialogs", "quests", "strings"):
                for p in glob_txt(os.path.join(self.content, f)):
                    if os.path.splitext(os.path.basename(p))[0].lower() == o:
                        self.only_srcs.add(self.rel(p))
            if not self.only_srcs:
                print('--only %s: такого источника нет (имя файла, entity или id квеста)' % self.args.only)
                return 2

        written = None
        vo_written = None
        tot = None
        if not self.args.check:
            written = self.write_outputs()
            vo_written, tot = self.write_vo_docs()

        # печать диагностики
        shown = []
        for it in self.D.items:
            level, src = it[0], it[1]
            if level == "note" and not self.args.verbose:
                continue
            if self.only_srcs and src not in self.only_srcs and src != "sound/vo/hl2rpm":
                continue
            shown.append(it)
        order = {"error": 0, "warn": 1, "note": 2}
        shown.sort(key=lambda x: (x[1], x[2], order[x[0]]))
        for it in shown:
            print(self.D.format(it))
        flt = [x for x in self.D.items if not self.only_srcs or x[1] in self.only_srcs]
        n_err = sum(1 for x in flt if x[0] == "error")
        n_warn = sum(1 for x in flt if x[0] == "warn")
        n_note = sum(1 for x in flt if x[0] == "note")

        if self.args.verbose:
            never = sorted(f for f in self.flags_req if f not in self.flags_set)
            if never:
                print("INFO  флаги проверяются, но не ставятся контентом (их может ставить карта): " + ", ".join(never))

        s = self.stats
        n_dlg_tok = sum(1 for t in self.tokens.values() if t.file == "dialog")
