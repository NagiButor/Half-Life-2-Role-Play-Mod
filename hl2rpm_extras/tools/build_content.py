    # ----------------------------------------------------------------- общее
    def rel(self, path):
        return os.path.relpath(path, self.content).replace("\\", "/")

    def read(self, path, src):
        try:
            text, problem = read_text_file(path)
        except OSError as e:
            self.D.error(src, 0, "", "не читается: %s" % e)
            return None
        if problem:
            self.D.warn(src, 0, "", problem)
        return text

    def parse_checked(self, text, src, multiline_level="error"):
        """Разбор с проверкой синтаксиса. -> root или None (тогда файл не проверяется и не собирается)."""
        before = sum(1 for x in self.D.items if x[0] == "error" and x[1] == src)
        root = kv_parse(text, src, self.D, multiline_level)
        errs = [x for x in self.D.items if x[0] == "error" and x[1] == src][before:]
        if errs:
            first = min(x[2] for x in errs)
            self.D.error(src, first, "", "синтаксическая ошибка (первая - в строке %d): файл не проверялся дальше "
                         "и не собран; в MOD остаётся прошлая сборка" % first)
            self.keep_outputs.add(src)
            return None
        return root

    def unknown_key(self, node, allowed, src, where, extra=""):
        k = node.k
        strict = k.startswith("require_") or k.startswith("on_success_") or k.startswith("on_fail_")
        cand = difflib.get_close_matches(k, list(allowed), n=1, cutoff=0.86 if strict else 0.75)
        if strict:
            self.D.error(src, node.line, where, 'неизвестный ключ "%s"%s - условие/эффект не сработает '
                         '(список - RPG_SPEC §3/§4)%s' % (node.key, (', может, "%s"?' % cand[0]) if cand else "", extra))
        elif cand:
            self.D.error(src, node.line, where, 'неизвестный ключ "%s" - может, "%s"?%s' % (_shown(node.key), cand[0], extra))
        else:
            self.D.warn(src, node.line, where, 'неизвестный ключ "%s" - игра его проигнорирует%s' % (_shown(node.key), extra))

    def check_block(self, blk, schema, src, where, conds=False, effects=False, on=False,
                    exclude_effects=(), hints=None):
        """Проверка ключей блока по схеме. Возвращает список (kind, node) для дальнейшей обработки."""
        def allowed_keys():
            allowed = set(schema) | SOURCE_ONLY
            allowed |= {k + "_en" for k, v in schema.items() if v == "text"}
            if conds:
                allowed |= COND_KEYS | {"hide_if_unmet"}
            if effects:
                allowed |= EFFECT_KEYS - set(exclude_effects)
            if on:
                allowed |= {"on_success_" + e for e in EFFECT_KEYS} | {"on_fail_" + e for e in EFFECT_KEYS}
            return allowed
        seen = collections.Counter()
        res = []
        for c in list(blk.children):
            k = c.k
            if k in SOURCE_ONLY:
                continue
            if k.endswith("_en") and schema.get(k[:-3]) == "text":
                kind = "text_en"
            elif k in schema:
                kind = schema[k]
            elif conds and (k in COND_KEYS or k == "hide_if_unmet"):
                kind = "bool" if k == "hide_if_unmet" else "cond"
            elif effects and k in EFFECT_KEYS and k not in exclude_effects:
                kind = "effect"
            elif on and (k.startswith("on_success_") or k.startswith("on_fail_")) and \
                    k.split("_", 2)[2] in EFFECT_KEYS:
                kind = "effect"
            else:
                hint = (hints or {}).get(k, "")
                self.unknown_key(c, allowed_keys(), src, where, hint)
                continue
            seen[k] += 1
            if kind == "block" and not c.is_block:
                self.D.error(src, c.line, where, '"%s" должен быть блоком { ... }, а не значением' % c.key)
                continue
            if kind != "block" and c.is_block:
                self.D.error(src, c.line, where, '"%s" должен быть значением, а не блоком { ... }' % c.key)
                continue
            if seen[k] == 2 and k not in REPEATABLE and not k.startswith("on_"):
                self.D.warn(src, c.line, where, 'ключ "%s" повторяется - игра возьмёт первый' % c.key)
            if kind not in ("block", "text", "text_en"):
                self.check_value(kind, c, src, where)
            res.append((kind, c))
        return res

    # ------------------------------------------------------- значения ключей
    def check_value(self, kind, c, src, where):
        v = c.value.strip()
        key = c.key
        if kind == "bool":
            lv = v.lower()
            if lv in ("0", "1"):
                return
            if lv in ("true", "yes", "да"):
                c.value = "1"
            elif lv in ("false", "no", "нет", ""):
                c.value = "0"
            else:
                self.D.error(src, c.line, where, '%s = "%s": ожидается 0 или 1' % (key, c.value))
                return
            self.D.note(src, c.line, where, '%s "%s" записан как "%s"' % (key, v, c.value))
        elif kind in ("int", "sint", "num", "node"):
            ok = is_int(v, kind != "int") if kind != "num" else re.fullmatch(r"[+-]?\d+(\.\d+)?", v)
            if not ok:
                self.D.error(src, c.line, where, '%s = "%s": ожидается %s' % (
                    key, c.value, "номер узла" if kind == "node" else "число"))
        elif kind == "delay":
            if v and v.lower() != "auto" and not re.fullmatch(r"\d+(\.\d+)?", v):
                self.D.error(src, c.line, where, 'option_delay = "%s": число секунд или auto' % c.value)
        elif kind == "vo":
            if not re.fullmatch(r"[A-Za-z0-9_]+", v):
                self.D.error(src, c.line, where, 'vo = "%s": только латиница, цифры и _ (это имя файла и токена)' % c.value)
            elif v != v.upper():
                self.D.warn(src, c.line, where, 'vo = "%s": принято писать ID заглавными (%s)' % (v, v.upper()))
        elif kind == "npc":
            self.check_npc(v, src, c.line, where)
        elif kind == "voice":
            if v.lower() not in NO_VOICE and v not in self.chars:
                self.voice_warned.add(v)
                self.D.warn(src, c.line, where, 'голос "%s" не описан в characters.txt' % v)
        elif kind == "check":
            self.check_check(c, src, where)
        elif kind == "map":
            if v and v not in SPEC_MAPS:
                self.D.warn(src, c.line, where, 'карта "%s" не из списка RPG_SPEC §11' % v)
        elif kind == "faction":
            if v and v not in self.factions:
                self.D.warn(src, c.line, where, 'фракция "%s" не из списка RPG_SPEC §11' % v)
        elif kind == "category":
            if v not in QUEST_CATEGORIES:
                self.D.error(src, c.line, where, 'category = "%s": одно из %s' % (v, "/".join(sorted(QUEST_CATEGORIES))))
        elif kind == "objtype":
            if v not in OBJECTIVE_TYPES:
                self.D.error(src, c.line, where, 'type = "%s": одно из %s' % (v, "/".join(sorted(OBJECTIVE_TYPES))))
        elif kind == "cond":
            self.check_cond(c, src, where)
        elif kind == "effect":
            self.check_effect(c, src, where)

    def check_npc(self, name, src, line, where):
        if not name:
            return
        n = name.lower()
        if n in SPEC_NPCS:
            return
        for p, _v in NPC_PATTERNS:
            if n.startswith(p):
                return
        if n in self.char_npc:
            self.D.note(src, line, where, 'NPC "%s" есть в characters.txt, но не в RPG_SPEC §11 - внесите в спецификацию' % name)
            return
        if src.split("/")[-1].startswith("_"):
            return
        # spot_* - точки диалога без NPC (info_target: сон, плакат, терминал)
        if n.startswith("spot_"):
            return
        self.D.warn(src, line, where, 'NPC "%s" не из списка RPG_SPEC §11 (и не в characters.txt)' % name)

    def check_item(self, cls, src, line, where):
        # цель «item» квеста принимает варианты через «;» (rpg_quest_data.cpp)
        for part in cls.split(";"):
            c = part.strip().lower()
            if not c or c in self.items or c in VANILLA_ITEMS or c.startswith(VANILLA_ITEM_PREFIXES):
                continue
            self.D.warn(src, line, where, 'предмет "%s" не из списка RPG_SPEC §11 / items.txt' % part.strip())

    def check_faction(self, f, src, line, where, scaled=True):
        if f in self.factions:
            return True
        if f in FACTIONS_SERVICE:
            if scaled:
                self.D.warn(src, line, where, 'у служебной фракции "%s" нет шкалы репутации (RPG_SPEC §11)' % f)
            return True
        self.D.warn(src, line, where, 'фракция "%s" не из списка RPG_SPEC §11' % f)
        return False

    def ref_quest(self, qid, src, line, where):
        self.quest_refs.append((qid.strip(), src, line, where))

    def check_flag_name(self, name, src, line, where):
        if not re.fullmatch(r"[A-Za-z0-9_.\-]+", name):
            self.D.error(src, line, where, 'имя флага "%s": только латиница, цифры, _ . -' % name)

    def check_check(self, c, src, where):
        v = c.value.strip()
        parts = v.split(":")
        kind = parts[0].lower()

        def num_ok(s):
            return re.fullmatch(r"\d+", s.strip()) is not None

        def part_ok(p):
            q = p.split(":")
            if len(q) == 3 and q[0].lower() in ("skill", "attr"):
                q = q[1:]
            if len(q) != 2 or not num_ok(q[1]):
                return False
            return q[0].lower() in SKILLS or q[0].lower() in ATTR_ALL

        if kind in ("skill", "attr") and len(parts) == 3:
            idl = parts[1].lower()
            if kind == "skill" and idl not in SKILLS:
                self.D.error(src, c.line, where, 'check "%s": навык "%s" не существует (%s)' % (v, parts[1], ", ".join(sorted(SKILLS))))
            if kind == "attr" and idl not in ATTR_ALL:
                self.D.error(src, c.line, where, 'check "%s": характеристика "%s" не существует (LOV/ANA/MIG/BDI/DUH/AVT)' % (v, parts[1]))
            if not num_ok(parts[2]):
                self.D.error(src, c.line, where, 'check "%s": порог должен быть числом' % v)
            return
        if kind in ("lie", "bribe", "barter") and len(parts) == 2:
            if not num_ok(parts[1]):
                self.D.error(src, c.line, where, 'check "%s": порог должен быть числом' % v)
            return
        if kind == "intimidate":
            rest = v.split(":", 1)[1] if ":" in v else ""
            alts = [p for p in rest.split("/") if p]
            if not alts or not all(part_ok(p) for p in alts):
                self.D.error(src, c.line, where, 'check "%s": формат intimidate:MIG:6/speech:40' % v)
            return
        if len(parts) == 2 and num_ok(parts[1]):
            if kind in SKILLS:
                c.value = "skill:%s:%s" % (kind, parts[1].strip())
                self.D.note(src, c.line, where, 'check "%s" записан как "%s"' % (v, c.value))
                return
            if kind in ATTR_ALL:
                c.value = "attr:%s:%s" % (parts[0].strip().upper() if kind in ATTR_ABBR else kind, parts[1].strip())
                self.D.note(src, c.line, where, 'check "%s" записан как "%s"' % (v, c.value))
                return
        self.D.error(src, c.line, where, 'check "%s": формат skill:<id>:N, attr:<id>:N, lie:N, bribe:N, barter:N '
                     'или intimidate:MIG:6/speech:40 (RPG_SPEC §5)' % v)

    def check_cond(self, c, src, where):
        k, v, ln = c.k, c.value.strip(), c.line
        E = lambda msg: self.D.error(src, ln, where, "%s \"%s\": %s" % (c.key, c.value, msg))
        if not v:
            E("пустое условие")
            return
        if k == "require":
            return
        if "," in v and k not in ("require",):
            E("одно условие на ключ - повторите ключ для второго условия")
            return
        num_keys = ("require_humanity", "require_resonance", "require_suspicion", "require_credits",
                    "require_level", "require_disposition")
        if k in num_keys or k == "require_civil":
            if k == "require_civil" and v.lower() in CIVIL_TIERS:
                return
            if re.fullmatch(r"[+-]?\d+", v):
                c.value = ">=" + v.lstrip("+")
                self.D.note(src, ln, where, '%s "%s" записан как "%s"' % (c.key, v, c.value))
                return
            if not re.fullmatch(OPS_RE + r"\s*[+-]?\d+", v):
                E("формат «op N», например >=20" + (" или уровень ГС (%s)" % "/".join(sorted(CIVIL_TIERS)) if k == "require_civil" else ""))
            return
        if k in ("require_attr", "require_skill"):
            m = re.fullmatch(r"([A-Za-z_]+)\s*" + OPS_RE + r"\s*(\d+)", v)
            if not m:
                E("формат «ID op N», например %s" % ("ANA<=3" if k == "require_attr" else "speech>=50"))
                return
            ident = m.group(1).lower()
            if k == "require_attr" and ident not in ATTR_ALL:
                E("нет характеристики %s (LOV/ANA/MIG/BDI/DUH/AVT)" % m.group(1))
            if k == "require_skill" and ident not in SKILLS:
                E("нет навыка %s (%s)" % (m.group(1), ", ".join(sorted(SKILLS))))
            return
        if k == "require_faction":
            m = re.fullmatch(r"([a-z_]+)\s*" + OPS_RE + r"\s*([+-]?\d+)", v) or re.fullmatch(r"([a-z_]+):([a-z]+)", v)
            if not m:
                E("формат «lambda>=25» или «lambda:recognized»")
                return
            self.check_faction(m.group(1), src, ln, where)
            if ":" in v and m.group(2) not in FACTION_TIERS:
                E("уровень фракции - один из %s" % "/".join(sorted(FACTION_TIERS)))
            return
        if k == "require_item":
            m = re.fullmatch(r"([A-Za-z0-9_]+)(?::(\d+))?", v)
            if not m:
                E("формат «classname[:N]»")
                return
            self.check_item(m.group(1), src, ln, where)
            return
        if k in ("require_perk", "require_trait"):
            pre = "PK" if k == "require_perk" else "TR"
            if not re.fullmatch(pre + r"-\d{2}", v):
                E("формат %s-NN" % pre)
                return
            known = self.perks if k == "require_perk" else self.traits
            if known and v not in known:
                self.D.warn(src, ln, where, '%s "%s": нет в scripts/rpg/%s.txt' % (c.key, v, "perks" if pre == "PK" else "traits"))
            elif not known and pre == "TR" and not (1 <= int(v[3:]) <= 12):
                self.D.warn(src, ln, where, '%s "%s": черты среза - TR-01..TR-12' % (c.key, v))
            return
        if k in ("require_flag", "require_noflag"):
            m = re.fullmatch(r"([A-Za-z0-9_.\-]+)(?:\s*" + OPS_RE + r"\s*(.+))?", v)
            if not m:
                E("формат «name», «name=value» или «name op N»")
                return
            self.flags_req[m.group(1)].append((src, ln))
            return
        if k == "require_act":
            if not re.fullmatch(r"\d+(-\d+)?", v):
                E("формат «N» или «N-M»")
            return
        if k == "require_time":
            if v.lower() not in ("day", "night", "curfew") and not re.fullmatch(r"\d{1,2}-\d{1,2}", v):
                E("day / night / curfew / H-H")
            return
        if k == "require_quest_state":
            m = re.fullmatch(r"([A-Za-z0-9_]+):([A-Za-z]+)", v)
            if not m:
                E("формат «quest_id:state»")
                return
            if m.group(2).lower() not in QUEST_STATES:
                E("состояние - одно из %s" % "/".join(sorted(QUEST_STATES)))
            self.ref_quest(m.group(1), src, ln, where)
            return
        if k == "require_quest_stage":
            m = re.fullmatch(r"([A-Za-z0-9_]+):(\d+)", v)
            if not m:
                E("формат «quest_id:N»")
                return
            self.ref_quest(m.group(1), src, ln, where)
            return
        if k == "require_quest":
            self.ref_quest(v, src, ln, where)
            return
        if k in ("require_rep", "require_stage"):
            if not is_int(v):
                E("ожидается число")

    def check_effect(self, c, src, where):
        k = c.k
        base = k.split("_", 2)[2] if (k.startswith("on_success_") or k.startswith("on_fail_")) else k
        v = c.value.strip()
        ln = c.line
        E = lambda msg: self.D.error(src, ln, where, "%s \"%s\": %s" % (c.key, c.value, msg))
        if base in LIST_EFFECTS and ";" in v:
            c.value = ", ".join(split_list(v))
            self.D.note(src, ln, where, '%s: разделитель ";" заменён на "," (RPG_SPEC §4)' % c.key)
            v = c.value
        items = split_list(v) if base in LIST_EFFECTS else [v]
        if not v and base not in ("start_combat", "open_chargen", "open_levelup"):
            E("пустое значение")
            return
        for it in items:
            if base == "xp":
                if not re.fullmatch(r"\+?\d+", it):
                    E("опыт - положительное число")
            elif base in ("civil", "suspicion", "humanity", "resonance", "influence", "credits",
                          "disposition"):
                if not re.fullmatch(r"[+-]?\d+", it):
                    E("ожидается число со знаком, например +5 или -10")
            elif base in ("damage", "heal"):
                if not re.fullmatch(r"\d+", it):
                    E("ожидается число")
            elif base == "rep":
                m = re.fullmatch(r"([a-z_]+)\s*:\s*([+-]?\d+)", it)
                if not m:
                    E("формат «lambda:+10, reapers:-5»")
                else:
                    self.check_faction(m.group(1), src, ln, where)
            elif base in ("give_item", "take_item"):
                m = re.fullmatch(r"([A-Za-z0-9_]+)(?::(\d+))?", it)
                if not m:
                    E("формат «item_ration:2, item_water_can»")
                else:
                    self.check_item(m.group(1), src, ln, where)
            elif base == "set_flag":
                name = it.split("=", 1)[0].strip()
                self.check_flag_name(name, src, ln, where)
                self.flags_set[name].append((src, ln))
            elif base == "clear_flag":
                self.check_flag_name(it, src, ln, where)
                self.flags_set[it].append((src, ln))
            elif base == "add_flag":
                m = re.fullmatch(r"([A-Za-z0-9_.\-]+)\s*[:=]\s*([+-]?\d+)", it)
                if not m:
                    E("формат «name:+1» (прибавить к числовому флагу)")
                else:
                    self.flags_set[m.group(1)].append((src, ln))
            elif base == "disposition_npc":
                m = re.fullmatch(r"([A-Za-z0-9_]+)\s*:\s*([+-]?\d+)", it)
                if not m:
                    E("формат «npc_ostap:-5»")
                else:
                    self.check_npc(m.group(1), src, ln, where)
            elif base in ("grant_quest", "complete_quest", "fail_quest"):
                if not re.fullmatch(r"[A-Za-z0-9_]+", it):
                    E("ожидается id квеста")
                else:
                    self.ref_quest(it, src, ln, where)
            elif base == "set_stage":
                m = re.fullmatch(r"([A-Za-z0-9_]+):(\d+)", it)
                if not m:
                    E("формат «quest_id:N»")
                else:
                    self.ref_quest(m.group(1), src, ln, where)
            elif base == "quest_event":
                m = re.fullmatch(r"([a-z]+):(.+)", it)
                if not m or m.group(1) not in QUEST_EVENT_TYPES:
                    E("формат «talk:npc_x», «reach:name», «event:name» (RPG_SPEC §6)")
                elif m.group(1) == "talk":
                    self.check_npc(m.group(2), src, ln, where)
            elif base == "discover":
                if it not in self.locations:
                    self.D.warn(src, ln, where, 'локация "%s" не из списка RPG_SPEC §11' % it)
            elif base in ("start_combat", "open_chargen", "open_levelup"):
                if it not in ("0", "1", ""):
                    E("ожидается 1")
            elif base == "haggle":
                if not re.match(r"^([A-Za-z0-9_]+:)?[+-]?\d+$", it):
                    E("ожидается [торговец:]N (проценты)")
            elif base == "open_barter":
                if it != "1" and self.traders and it not in self.traders:
                    self.D.warn(src, ln, where, 'торговец "%s" не найден в scripts/rpg/traders.txt' % it)
            elif base == "fire":
                if len(it.split(",")) < 2:
                    E("формат «target,Input,param,delay»")
            elif base in ("notify", "sound"):
                pass

