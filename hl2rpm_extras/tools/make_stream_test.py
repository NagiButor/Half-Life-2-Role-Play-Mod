#!/usr/bin/env python3
"""Test map for the entity streaming of HL2RPM (game/server/hl2rpm/rpg_streaming.cpp, RPG_SPEC 11.2).

    python make_stream_test.py [<out.vmf>]      (default: mapsrc/test/stream_test.vmf)

A flat 14000 x 14000 field (the new_test_map shell) with 2600 entities marked rpg_stream 1:
2200 physics crates on a jittered grid and 400 citizens - more than the engine's 2048 edicts, so the
map only loads because streamed entities are not created with the map. A few pillars give the
field landmarks; the player starts in a corner. Check with rpg_stream_info (live / stored counts,
edicts in use) while walking (noclip, sv_noclipspeed), rpg_stream_debug 2 draws the homes.
Compile: compile_map.ps1 -Map stream_test -Profile quick
"""
import os
import random
import sys

sys.path.insert(0, r"E:\SourceModding\HL2RPMSOURCE\.claude\skills\hl2rpm-hammer\scripts")
import new_test_map  # noqa: E402
from vmf import VMF  # noqa: E402

MAPSRC = r"E:\XBLAH's modding tool\content\Mapbase\hl2rpm\mapsrc"
SIZE = 14000
CRATES = 2200
CITIZENS = 400


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(MAPSRC, "test", "stream_test.vmf")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    new_test_map.main(["new_test_map.py", out, "--size", str(SIZE), "--height", "1024"])
    m = VMF.load(out)
    rnd = random.Random(17)
    h = SIZE / 2 - 200
    # pillars as landmarks every 2000 units
    for x in range(-6000, 6001, 2000):
        for y in range(-6000, 6001, 2000):
            if x or y:
                m.add_box((x - 48, y - 48, 0), (x + 48, y + 48, 384), "DEV/DEV_MEASUREWALL01A")
    n = int(CRATES ** 0.5) + 1
    step = 2 * h / n
    k = 0
    for i in range(n):
        for j in range(n):
            if k >= CRATES:
                break
            x = -h + (i + 0.5) * step + rnd.uniform(-step * 0.3, step * 0.3)
            y = -h + (j + 0.5) * step + rnd.uniform(-step * 0.3, step * 0.3)
            m.add_entity("prop_physics", (round(x), round(y), 24), model="models/props_junk/wood_crate001a.mdl",
                         angles="0 %d 0" % rnd.randint(0, 359), spawnflags="256", rpg_stream="1",
                         targetname="stream_crate_%d" % k)
            k += 1
    models = ["models/humans/group01/male_0%d.mdl" % i for i in (1, 2, 3, 4, 6, 7, 8, 9)] + \
             ["models/humans/group01/female_0%d.mdl" % i for i in (1, 2, 3, 4, 6, 7)]
    for c in range(CITIZENS):
        x, y = rnd.uniform(-h, h), rnd.uniform(-h, h)
        m.add_entity("npc_citizen", (round(x), round(y), 8), angles="0 %d 0" % rnd.randint(0, 359),
                     model=rnd.choice(models), citizentype="4", expressiontype="Random", spawnflags="16777216",
                     rpg_stream="1", rpg_faction="citizen", targetname="stream_cit_%d" % c)
    m.world.set("comment", "HL2RPM streaming test, generated by hl2rpm_extras/tools/make_stream_test.py")
    m.save(out, backup=False)
    print("wrote", out, "(%d crates, %d citizens streamed)" % (k, CITIZENS))


if __name__ == "__main__":
    main()
